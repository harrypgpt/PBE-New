import { z } from 'zod';
import { ProblemDetailsSchema } from './problem-details';
import { defineRoute, type RouteContract } from './route';
import {
  DOSAGE_FORM_CODES,
  PRODUCT_FLAG_CODES,
  RELEASE_TYPE_CODES,
  ROUTE_CODES,
  STRENGTH_UNITS,
} from './vocabulary';

/**
 * Stage 8 contracts (STAGE-08-PLAN.md D8-3 to D8-8; ADR-030): project input, projects and
 * scenarios routes. Every term must come from the controlled vocabulary. Like the tenancy routes,
 * these act on the session's ACTIVE organisation only; no organisation id is taken from the request.
 */
export const ProjectInputSchema = z.strictObject({
  name: z.string().trim().min(1).max(200),
  molecule: z.string().trim().min(1).max(200),
  strength: z.strictObject({
    value: z.number().finite().positive().max(1_000_000),
    unit: z.enum(STRENGTH_UNITS),
  }),
  dosageForm: z.enum(DOSAGE_FORM_CODES),
  route: z.enum(ROUTE_CODES),
  releaseType: z.enum(RELEASE_TYPE_CODES),
  productFlags: z
    .array(z.enum(PRODUCT_FLAG_CODES))
    .max(PRODUCT_FLAG_CODES.length)
    .refine((flags) => new Set(flags).size === flags.length, { message: 'Each flag at most once.' })
    .default([]),
});
export type ProjectInput = z.infer<typeof ProjectInputSchema>;

/** Scenario codes F001, F002, … (D8-7): generated by the system, never typed in. */
export const SCENARIO_CODE_PATTERN = /^F\d{3,}$/;

export const ScenarioInputSchema = z.strictObject({
  description: z.string().trim().max(500).default(''),
});

// --- Shapes -------------------------------------------------------------------------------------
const Id = z.uuid();
const Timestamp = z.iso.datetime();

/** Departments that may see the project (D8-6); none = every member with tenant.projects.read. */
const DepartmentIds = z
  .array(Id)
  .max(50)
  .refine((ids) => new Set(ids).size === ids.length, { message: 'Each department at most once.' })
  .default([]);

export const ProjectWriteSchema = ProjectInputSchema.extend({ departmentIds: DepartmentIds });
export type ProjectWrite = z.infer<typeof ProjectWriteSchema>;

export const ScopeInputSchema = ProjectInputSchema.pick({
  dosageForm: true,
  route: true,
  releaseType: true,
  productFlags: true,
});

export const ScopeResultSchema = z.strictObject({
  status: z.enum(['supported', 'unsupported']),
  reasons: z.array(z.string()),
  /** At least one reason is a borderline term awaiting the scientific reviewer (OD-10). */
  awaitingReviewer: z.boolean(),
  vocabularyVersion: z.string(),
});
export type ScopeResultDto = z.infer<typeof ScopeResultSchema>;

export const ScenarioSchema = z.strictObject({
  id: Id,
  code: z.string().regex(SCENARIO_CODE_PATTERN),
  description: z.string(),
  createdAt: Timestamp,
  updatedAt: Timestamp,
});
export type ScenarioDto = z.infer<typeof ScenarioSchema>;

export const ProjectSchema = z.strictObject({
  id: Id,
  name: z.string(),
  molecule: z.string(),
  strength: z.strictObject({ value: z.number(), unit: z.string() }),
  dosageForm: z.string(),
  route: z.string(),
  releaseType: z.string(),
  productFlags: z.array(z.string()),
  /** As computed when the project was last saved, with the vocabulary version used. */
  scope: z.strictObject({
    status: z.enum(['supported', 'unsupported']),
    reasons: z.array(z.string()),
    vocabularyVersion: z.string(),
  }),
  status: z.enum(['active', 'archived']),
  departmentIds: z.array(Id),
  scenarioCount: z.number().int().min(0),
  createdAt: Timestamp,
  updatedAt: Timestamp,
});
export type ProjectDto = z.infer<typeof ProjectSchema>;

export const ProjectDetailSchema = ProjectSchema.extend({ scenarios: z.array(ScenarioSchema) });
export type ProjectDetailDto = z.infer<typeof ProjectDetailSchema>;

// --- Routes -------------------------------------------------------------------------------------
const problem = (description: string) => ({ description, schema: ProblemDetailsSchema });
const STD = {
  400: problem('Malformed request or rule not met.'),
  401: problem('Not signed in.'),
  403: problem('Permission or origin check failed.'),
  404: problem('Not found, or not visible to you, in this organisation.'),
} as const;
const ARCHIVED = { 409: problem('The project is archived and can no longer be changed.') } as const;
const projectParam = z.strictObject({ projectId: Id });

export const projectsListRoute = defineRoute({
  operationId: 'getProjects',
  method: 'GET',
  path: '/projects',
  summary: 'Projects of the active organisation that you may see',
  access: { kind: 'permission', permission: 'tenant.projects.read' },
  request: {},
  responses: {
    200: { description: 'Projects.', schema: z.strictObject({ projects: z.array(ProjectSchema) }) },
    ...STD,
  },
});

export const projectScopeCheckRoute = defineRoute({
  operationId: 'postProjectScopeCheck',
  method: 'POST',
  path: '/projects/scope-check',
  summary: 'Check product terms against the supported scope (ADR-011); stores nothing',
  access: { kind: 'permission', permission: 'tenant.projects.read' },
  request: { body: ScopeInputSchema },
  responses: { 200: { description: 'Scope result.', schema: ScopeResultSchema }, ...STD },
});

export const projectCreateRoute = defineRoute({
  operationId: 'postProject',
  method: 'POST',
  path: '/projects',
  summary: 'Create a project (an unsupported product is recorded and marked, with the reason)',
  access: { kind: 'permission', permission: 'tenant.projects.create' },
  request: { body: ProjectWriteSchema },
  responses: {
    201: { description: 'Created.', schema: z.strictObject({ project: ProjectDetailSchema }) },
    ...STD,
  },
});

export const projectGetRoute = defineRoute({
  operationId: 'getProject',
  method: 'GET',
  path: '/projects/:projectId',
  summary: 'A project with its scenarios',
  access: { kind: 'permission', permission: 'tenant.projects.read' },
  request: { params: projectParam },
  responses: {
    200: { description: 'Project.', schema: z.strictObject({ project: ProjectDetailSchema }) },
    ...STD,
  },
});

export const projectUpdateRoute = defineRoute({
  operationId: 'putProject',
  method: 'PUT',
  path: '/projects/:projectId',
  summary: 'Change a project (the scope is checked again)',
  access: { kind: 'permission', permission: 'tenant.projects.manage' },
  request: { params: projectParam, body: ProjectWriteSchema },
  responses: {
    200: { description: 'Changed.', schema: z.strictObject({ project: ProjectDetailSchema }) },
    ...STD,
    ...ARCHIVED,
  },
});

export const projectArchiveRoute = defineRoute({
  operationId: 'postProjectArchive',
  method: 'POST',
  path: '/projects/:projectId/archive',
  summary: 'Archive a project: it stays visible and becomes read-only (D8-8)',
  access: { kind: 'permission', permission: 'tenant.projects.manage' },
  request: { params: projectParam },
  responses: {
    200: { description: 'Archived.', schema: z.strictObject({ project: ProjectDetailSchema }) },
    ...STD,
    ...ARCHIVED,
  },
});

export const scenarioCreateRoute = defineRoute({
  operationId: 'postScenario',
  method: 'POST',
  path: '/projects/:projectId/scenarios',
  summary: 'Add a scenario; its code (F001, F002, …) is generated and never reused (D8-7)',
  access: { kind: 'permission', permission: 'tenant.scenarios.manage' },
  request: { params: projectParam, body: ScenarioInputSchema },
  responses: {
    201: { description: 'Added.', schema: z.strictObject({ scenario: ScenarioSchema }) },
    ...STD,
    ...ARCHIVED,
  },
});

export const scenarioUpdateRoute = defineRoute({
  operationId: 'putScenario',
  method: 'PUT',
  path: '/projects/:projectId/scenarios/:scenarioId',
  summary: 'Change a scenario’s description (the code never changes)',
  access: { kind: 'permission', permission: 'tenant.scenarios.manage' },
  request: {
    params: z.strictObject({ projectId: Id, scenarioId: Id }),
    body: ScenarioInputSchema,
  },
  responses: {
    200: { description: 'Changed.', schema: z.strictObject({ scenario: ScenarioSchema }) },
    ...STD,
    ...ARCHIVED,
  },
});

export const PROJECT_ROUTES: readonly RouteContract[] = [
  projectsListRoute,
  projectScopeCheckRoute,
  projectCreateRoute,
  projectGetRoute,
  projectUpdateRoute,
  projectArchiveRoute,
  scenarioCreateRoute,
  scenarioUpdateRoute,
];
