import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { migrationsDir } from '../../tooling/migrate/src/config';
import { migrate, status } from '../../tooling/migrate/src/runner';
import {
  TYPEGEN_SCHEMAS,
  readColumnMetadata,
  renderTypes,
} from '../../tooling/migrate/src/typegen';
import { assertTestSchema, dbConfig, ROOT, testSchemaSql, withClient } from './helpers';

// T12: the in-house type generator against real PostgreSQL 18 metadata (pbe_test).

const COMMITTED = path.join(ROOT, 'apps', 'api', 'src', 'modules', 'db', 'database-types.ts');
const S = assertTestSchema(`zz_test_${randomBytes(5).toString('hex')}`);

const generate = async (schemas: readonly string[]) => {
  const st = await status({ connection: dbConfig('migrator'), migrationsDir: migrationsDir(ROOT) });
  const versions = st.entries.filter((e) => e.state === 'applied').map((e) => e.version);
  const meta = await withClient(dbConfig('migrator'), (c) => readColumnMetadata(c, schemas));
  return renderTypes(meta.columns, meta.enums, { versions, schemas });
};

beforeAll(async () => {
  await migrate({ connection: dbConfig('migrator'), migrationsDir: migrationsDir(ROOT) });
});
afterAll(async () => {
  await testSchemaSql(S, `DROP SCHEMA IF EXISTS ${S} CASCADE`);
});

describe('type generator on real PostgreSQL metadata', () => {
  it('the committed apps/api database types match the migrated pbe_test exactly', async () => {
    expect(await generate(TYPEGEN_SCHEMAS)).toBe(fs.readFileSync(COMMITTED, 'utf8'));
  });

  it('is deterministic: two runs produce identical output', async () => {
    expect(await generate(TYPEGEN_SCHEMAS)).toBe(await generate(TYPEGEN_SCHEMAS));
  });

  it('maps real enums, arrays, domains, identity, generated, defaults and nullability', async () => {
    await testSchemaSql(S, `CREATE SCHEMA ${S}`);
    await testSchemaSql(
      S,
      `CREATE TYPE ${S}.design AS ENUM ('crossover', 'parallel');
       CREATE DOMAIN ${S}.ratio AS numeric CHECK (VALUE > 0);
       CREATE TABLE ${S}.sample (
         id      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
         seq     integer GENERATED BY DEFAULT AS IDENTITY,
         design  ${S}.design NOT NULL,
         designs ${S}.design[],
         ratio   ${S}.ratio,
         tags    text[] NOT NULL DEFAULT '{}',
         amount  numeric(12, 4) NOT NULL,
         doubled numeric GENERATED ALWAYS AS (amount * 2) STORED,
         note    text
       )`,
    );
    const out = await generate([S]);
    const iface = out.slice(
      out.indexOf('export interface ZzTest'),
      out.indexOf('export interface DB'),
    );
    expect(iface).toContain('  id: GeneratedAlways<string>;');
    expect(iface).toContain('  seq: Generated<number>;');
    expect(iface).toContain('  design: "crossover" | "parallel";');
    expect(iface).toContain('  designs: ("crossover" | "parallel")[] | null;');
    expect(iface).toContain('  ratio: string | null;');
    expect(iface).toContain('  tags: Generated<string[]>;');
    expect(iface).toContain('  amount: string;');
    expect(iface).toContain('  doubled: GeneratedAlways<string | null>;');
    expect(iface).toContain('  note: string | null;');
  });

  it('stops on an unsupported real column type and names it', async () => {
    await testSchemaSql(S, `CREATE TABLE ${S}.odd (id integer, gap interval, doc tsvector)`);
    await expect(generate([S])).rejects.toMatchObject({
      code: 'TYPEGEN_UNSUPPORTED',
      details: [`${S}.odd.gap: interval`, `${S}.odd.doc: tsvector`], // table column order
    });
  });
});
