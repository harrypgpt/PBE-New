import fs from 'node:fs';
import path from 'node:path';
import pg from 'pg';
import type { ClientConfig } from 'pg';
import { backupAccessMatrix, formatAccessMatrix } from './access-matrix';
import {
  compareBackupFiles,
  backupDatabase,
  dropDisposableDatabase,
  readArchive,
  restoreDrill,
} from './backup';
import {
  OWNER_ROLE,
  PBE_SCHEMAS,
  TEST_SCHEMA_PATTERN,
  clientConfig,
  describeTarget,
  findRepoRoot,
  loadDbEnv,
  migrationsDir,
  snapshotFile,
  type DatabaseKind,
} from './config';
import { backupCoverageViolations, backupPrivilegeAudit } from './conformance';
import { MigrationError } from './errors';
import { diffFingerprints, schemaFingerprint, snapshotLines } from './fingerprint';
import { migrate, status } from './runner';
import { TYPEGEN_SCHEMAS, readColumnMetadata, renderTypes } from './typegen';

/** Committed output of the type generator (ADR-021). */
const TYPES_FILE = path.join('apps', 'api', 'src', 'modules', 'db', 'database-types.ts');

// ADR-020: pbe_dev = development, pbe_test = automated tests, pbe_restore_check_<hex> = temporary.
const USAGE = `Usage: npm run db -- <command> [options]

Commands
  status  [--db dev|test]                 List applied, pending and problem migrations (read-only)
  migrate [--db dev|test] [--allow-contract]
                                          Apply pending migrations (dev: also refreshes db/schema-snapshot.txt)
  drift                                   pbe_dev vs db/schema-snapshot.txt AND vs pbe_test (rebuilt by the tests)
  snapshot                                Re-write db/schema-snapshot.txt from pbe_dev
  backup  [--db dev|test]                 pg_dump to backups/<database>-<timestamp>.dump and decode it
  restore-drill [--db test|dev]           Backup → restore into a temporary database → verify → drop it
  compare-backups --first <file> --second <file> [--allow-new <schema.table,…>]
                                          Restore two backup files into temporary databases and
                                          compare every table's data (ledger reported separately)
  verify-backup-access [--socket-dir /tmp] Backup login: connection matrix (TCP IPv4/IPv6, sockets,
                                          replication), least-privilege audit and coverage (read-only)
  drop-disposable --database <name>       Drop a kept pbe_restore_check_<hex> database (refuses anything else)
  clean-test-schemas                      Drop leftover zz_test_* schemas in pbe_test
  typegen [--check]                       Generate apps/api database types from pbe_test (--check: fail if stale)`;

const SNAPSHOT_HEADER =
  '# PBE expected schema fingerprint. Generated by `npm run db -- migrate` (pbe_dev) or `snapshot`.\n' +
  '# Do not edit by hand. `npm run db -- drift` fails if pbe_dev differs from this file.\n';

function option(args: string[], name: string): string | undefined {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
}

function dbKind(args: string[], fallback: DatabaseKind): DatabaseKind {
  const value = option(args, '--db') ?? fallback;
  if (value !== 'dev' && value !== 'test') {
    throw new MigrationError('CONFIG', `--db must be dev or test (got "${value}").`);
  }
  return value;
}

async function withClient<T>(config: ClientConfig, fn: (c: pg.Client) => Promise<T>): Promise<T> {
  const client = new pg.Client(config);
  await client.connect();
  try {
    return await fn(client);
  } finally {
    await client.end();
  }
}

async function writeSnapshot(root: string, config: ClientConfig): Promise<number> {
  const lines = snapshotLines(await withClient(config, (c) => schemaFingerprint(c, PBE_SCHEMAS)));
  fs.writeFileSync(snapshotFile(root), `${SNAPSHOT_HEADER}${lines.join('\n')}\n`);
  return lines.length;
}

function readSnapshot(root: string): string[] {
  const file = snapshotFile(root);
  if (!fs.existsSync(file)) {
    throw new MigrationError(
      'CONFIG',
      'db/schema-snapshot.txt not found. Run "npm run db -- migrate".',
    );
  }
  return fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .filter((l) => l && !l.startsWith('#'));
}

/**
 * Who reads a database for a backup (STAGE-07A-BACKUP-REVIEW.md): the dedicated backup login
 * (pbe_backup, read-only, BYPASSRLS) when configured; otherwise, legacy, pbe_migrator acting as
 * pbe_owner, which cannot read tables with FORCED row-level security and therefore fails loudly.
 */
function backupSource(env: ReturnType<typeof loadDbEnv>, kind: 'dev' | 'test') {
  if (env.passwords.backup) {
    return {
      connection: clientConfig(env, kind, 'backup'),
      dumpRole: null,
      coverageRole: env.users.backup,
    };
  }
  console.log(
    'Note: backup login (pbe_backup) not configured; using pbe_migrator as pbe_owner. Databases with forced row-level security cannot be backed up this way.',
  );
  return {
    connection: clientConfig(env, kind, 'migrator'),
    dumpRole: OWNER_ROLE,
    coverageRole: undefined,
  };
}

function stamp(): string {
  return new Date().toISOString().replace(/[:.]/g, '-');
}

async function main(argv: string[]): Promise<number> {
  const [command, ...args] = argv;
  const root = findRepoRoot();
  const env = loadDbEnv(root);
  const dir = migrationsDir(root);

  switch (command) {
    case 'status': {
      const connection = clientConfig(env, dbKind(args, 'dev'), 'migrator');
      const report = await status({ connection, migrationsDir: dir });
      console.log(
        `Database: ${describeTarget(connection)}   ledger: ${report.ledgerExists ? 'present' : 'not created yet'}`,
      );
      for (const e of report.entries) {
        const when = e.appliedAt ? e.appliedAt.toISOString() : '';
        console.log(
          `  ${String(e.version).padStart(4, '0')}  ${e.state.padEnd(13)} ${(e.phase ?? '').padEnd(8)} ${e.name}  ${e.checksum ? e.checksum.slice(0, 16) : ''}  ${when}`,
        );
      }
      for (const p of report.problems) console.error(`  PROBLEM: ${p}`);
      console.log(
        report.ok
          ? `OK — ${report.pending} pending.`
          : 'PROBLEMS FOUND — migrate will refuse to run.',
      );
      return report.ok ? 0 : 1;
    }
    case 'migrate': {
      const kind = dbKind(args, 'dev');
      const connection = clientConfig(env, kind, 'migrator');
      console.log(`Migrating ${describeTarget(connection)}`);
      const result = await migrate({
        connection,
        migrationsDir: dir,
        allowContract: args.includes('--allow-contract'),
        log: (line) => console.log(`  ${line}`),
      });
      console.log(
        `Done: ${result.applied.length} applied, ${result.alreadyApplied} already applied.`,
      );
      if (kind === 'dev' && (result.applied.length > 0 || !fs.existsSync(snapshotFile(root)))) {
        const n = await writeSnapshot(root, connection);
        console.log(`Schema snapshot refreshed: db/schema-snapshot.txt (${n} entries).`);
      }
      return 0;
    }
    case 'snapshot': {
      const n = await writeSnapshot(root, clientConfig(env, 'dev', 'migrator'));
      console.log(`Schema snapshot written: db/schema-snapshot.txt (${n} entries).`);
      return 0;
    }
    case 'drift': {
      const dev = await withClient(clientConfig(env, 'dev', 'migrator'), (c) =>
        schemaFingerprint(c, PBE_SCHEMAS),
      );
      const test = await withClient(clientConfig(env, 'test', 'migrator'), (c) =>
        schemaFingerprint(c, PBE_SCHEMAS),
      );
      let ok = true;
      for (const [label, other, mine] of [
        ['db/schema-snapshot.txt', readSnapshot(root), snapshotLines(dev)],
        [`${env.databases.test} (rebuilt from scratch by the tests)`, test, dev],
      ] as const) {
        const diff = diffFingerprints(other, mine);
        if (diff.equal) {
          console.log(`No drift: ${env.databases.dev} matches ${label} (${dev.length} entries).`);
        } else {
          ok = false;
          console.error(`DRIFT: ${env.databases.dev} differs from ${label}`);
          for (const l of diff.onlyInFirst)
            console.error(`  missing in ${env.databases.dev}: ${l}`);
          for (const l of diff.onlyInSecond) console.error(`  only in ${env.databases.dev}: ${l}`);
        }
      }
      return ok ? 0 : 1;
    }
    case 'backup': {
      const { connection, dumpRole, coverageRole } = backupSource(env, dbKind(args, 'dev'));
      if (coverageRole !== undefined) {
        const problems = await withClient(connection, (c) =>
          backupCoverageViolations(c, coverageRole, OWNER_ROLE),
        );
        if (problems.length > 0) {
          throw new MigrationError(
            'UNSAFE_TARGET',
            `Backup coverage check failed: ${coverageRole} cannot read or verify everything. Nothing was backed up.`,
            problems,
          );
        }
      }
      const out = path.join(root, 'backups', `${connection.database}-${stamp()}.dump`);
      const result = backupDatabase(env.binDir, connection, out, dumpRole);
      const archive = readArchive(env.binDir, result.file);
      console.log(
        `Backup written: ${path.relative(root, result.file)} (${result.bytes} bytes, sha256 ${result.sha256})`,
      );
      console.log(
        `Archive decoded: ${archive.tocEntries} TOC entries, schemas ${[...archive.schemas].sort().join(', ')}, ${archive.ledger.length} ledger rows.`,
      );
      return 0;
    }
    case 'restore-drill': {
      const {
        connection: source,
        dumpRole,
        coverageRole,
      } = backupSource(env, dbKind(args, 'test'));
      const report = await restoreDrill({
        binDir: env.binDir,
        source,
        dumpRole,
        ...(coverageRole !== undefined ? { coverageRole } : {}),
        restore: clientConfig(env, 'test', 'restore'),
        ownerRole: OWNER_ROLE,
        migrationsDir: dir,
        schemas: PBE_SCHEMAS,
        backupFile: path.join(root, 'backups', `${source.database}-${stamp()}.dump`),
        excludeSchemas: ['zz_test_*'],
        log: (line) => console.log(`  ${line}`),
      });
      const c = report.comparison;
      console.log(`Source ${report.source} → restored into ${report.restoredInto}`);
      console.log(
        `  schema: ${c.fingerprint.equal ? 'identical' : 'DIFFERENT'} (${c.fingerprintEntries} entries); ledger: ${c.ledger.equal ? 'identical' : 'DIFFERENT'} (${c.ledger.target} rows)`,
      );
      for (const t of c.tables) {
        console.log(
          `  ${t.table}: rows ${t.sourceRows} → ${t.targetRows}, contents ${t.contentEqual ? 'identical' : 'DIFFERENT'}`,
        );
      }
      console.log(
        `  usable: status ${report.usable.statusOk ? 'ok' : 'NOT OK'}, ${report.usable.pending} pending, migrate applied ${report.usable.migrateApplied}, write/read ${report.usable.writeReadOk ? 'ok' : 'FAILED'}`,
      );
      console.log(`  temporary database ${report.cleanedUp ? 'dropped' : 'KEPT for diagnosis'}`);
      if (!report.ok) {
        const diag = path.join(root, 'backups', `restore-drill-${stamp()}.json`);
        fs.writeFileSync(diag, JSON.stringify(report, null, 2));
        console.error(`RESTORE DRILL FAILED — diagnostics: ${path.relative(root, diag)}`);
        return 1;
      }
      console.log('RESTORE DRILL PASSED');
      return 0;
    }
    case 'compare-backups': {
      const first = option(args, '--first');
      const second = option(args, '--second');
      if (!first || !second) {
        throw new MigrationError(
          'CONFIG',
          'compare-backups needs --first <file> and --second <file>.',
        );
      }
      for (const f of [first, second]) readArchive(env.binDir, f); // must decode completely
      const report = await compareBackupFiles({
        binDir: env.binDir,
        restore: clientConfig(env, 'test', 'restore'),
        first,
        second,
        schemas: PBE_SCHEMAS,
        onlyInSecond: (option(args, '--allow-new') ?? '').split(',').filter(Boolean),
      });
      console.log(
        `Ledger: first [${report.ledger.first.join(', ')}], second [${report.ledger.second.join(', ')}]`,
      );
      for (const t of report.tables) {
        console.log(
          `  ${t.table}: rows ${t.firstRows ?? '—'} → ${t.secondRows ?? '—'}, ${t.contentEqual ? 'same data' : 'DIFFERENT'}`,
        );
      }
      console.log(report.ok ? 'BACKUPS HOLD THE SAME DATA' : 'BACKUPS DIFFER');
      return report.ok ? 0 : 1;
    }
    case 'verify-backup-access': {
      const password = env.passwords.backup;
      if (!password) {
        throw new MigrationError(
          'CONFIG',
          'PBE_PG_BACKUP_PASSWORD is not set. Run "npm run db:bootstrap".',
        );
      }
      const user = env.users.backup;
      const cells = await backupAccessMatrix({
        port: env.port,
        socketDirs: [option(args, '--socket-dir') ?? '/tmp'],
        user,
        password,
        allowed: [env.databases.dev, env.databases.test],
      });
      console.log(`Connection matrix for ${user} (real connection attempts):`);
      console.log(formatAccessMatrix(cells));
      let failures = cells.filter((c) => !c.ok).length;
      for (const kind of ['dev', 'test'] as const) {
        const conn = clientConfig(env, kind, 'migrator');
        const [audit, coverage] = await withClient(
          conn,
          async (c) =>
            [
              await backupPrivilegeAudit(c, user),
              await backupCoverageViolations(c, user, OWNER_ROLE),
            ] as const,
        );
        console.log(
          `\n${conn.database}: least-privilege audit ${audit.violations.length === 0 ? 'PASS' : 'FAIL'}; coverage ${coverage.length === 0 ? 'PASS' : 'FAIL'}`,
        );
        for (const line of [...audit.violations, ...coverage]) console.log(`  - ${line}`);
        console.log(
          `  databases whose ACL allows CONNECT (pg_hba.conf must refuse all but PBE): ${audit.connectable.join(', ')}`,
        );
        failures += audit.violations.length + coverage.length;
      }
      console.log(
        failures === 0
          ? '\nBACKUP ACCESS VERIFIED'
          : `\nBACKUP ACCESS NOT VERIFIED: ${failures} problem(s)`,
      );
      return failures === 0 ? 0 : 1;
    }
    case 'drop-disposable': {
      const name = option(args, '--database');
      if (!name) throw new MigrationError('CONFIG', 'drop-disposable needs --database <name>.');
      await dropDisposableDatabase(clientConfig(env, 'test', 'restore'), name);
      console.log(`Dropped ${name}.`);
      return 0;
    }
    case 'clean-test-schemas': {
      const dropped = await withClient(clientConfig(env, 'test', 'migrator'), async (c) => {
        await c.query(`SET ROLE ${OWNER_ROLE}`);
        const { rows } = await c.query<{ nspname: string }>(
          "SELECT nspname FROM pg_catalog.pg_namespace WHERE nspname LIKE 'zz\\_test\\_%' ORDER BY 1",
        );
        const names = rows.map((r) => r.nspname).filter((n) => TEST_SCHEMA_PATTERN.test(n));
        for (const n of names) await c.query(`DROP SCHEMA ${c.escapeIdentifier(n)} CASCADE`);
        return names;
      });
      console.log(
        dropped.length
          ? `Dropped ${dropped.length}: ${dropped.join(', ')}`
          : 'No leftover test schemas.',
      );
      return 0;
    }
    case 'typegen': {
      const connection = clientConfig(env, 'test', 'migrator');
      const st = await status({ connection, migrationsDir: dir });
      if (!st.ok || st.pending > 0) {
        throw new MigrationError(
          'CONFIG',
          `${env.databases.test} must be fully migrated before generating types (${st.pending} pending${st.ok ? '' : ', problems found'}). Run: npm run db -- migrate --db test`,
        );
      }
      const versions = st.entries.filter((e) => e.state === 'applied').map((e) => e.version);
      const { columns, enums } = await withClient(connection, (c) =>
        readColumnMetadata(c, TYPEGEN_SCHEMAS),
      );
      const output = renderTypes(columns, enums, { versions, schemas: TYPEGEN_SCHEMAS });
      const target = path.join(root, TYPES_FILE);
      if (args.includes('--check')) {
        const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
        if (current !== output) {
          throw new MigrationError(
            'TYPEGEN_STALE',
            `${TYPES_FILE} is out of date with the migrated database. Run: npm run db -- typegen`,
          );
        }
        console.log(`Database types up to date: ${TYPES_FILE} (${columns.length} columns).`);
        return 0;
      }
      fs.writeFileSync(target, output);
      console.log(`Database types written: ${TYPES_FILE} (${columns.length} columns).`);
      return 0;
    }
    default:
      console.log(USAGE);
      return command ? 2 : 0;
  }
}

main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code;
  },
  (err: unknown) => {
    if (err instanceof MigrationError) {
      console.error(`ERROR [${err.code}] ${err.message}`);
      for (const d of err.details) console.error(`  - ${d}`);
    } else {
      console.error(`ERROR ${err instanceof Error ? err.message : String(err)}`);
    }
    process.exitCode = 1;
  },
);
